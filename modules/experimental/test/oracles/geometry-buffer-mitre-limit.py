"""Writes test/gpu-spatial-analysis/polygon-buffer/polygon-buffer-mitre-limit-fixtures.ts.

Oracle: shapely.buffer (mitre_limit 5, the GPUBufferSurface default) for review suspicion D S-4:
mitre-limited corners of a positive buffer (a 19-degree spike) and of a negative buffer (a narrow
notch, whose reflex vertex becomes a convex corner of the eroded polygon), and a round-join
negative buffer that splits a dumbbell at its neck. The fixture format is the one of
polygon-buffer-fixtures.ts: area plus a membership grid ('?' within 0.06 of the boundary).

Run: <venv>/bin/python -I test/oracles/geometry-buffer-mitre-limit.py (from modules/experimental).
"""
import json
import os

import shapely
from shapely.geometry import Point, Polygon

HERE = os.path.dirname(os.path.abspath(__file__))
DESTINATION = os.path.join(
    HERE, '..', 'gpu-spatial-analysis', 'polygon-buffer', 'polygon-buffer-mitre-limit-fixtures.ts'
)
cases = []


def add(name, polygon, distance, join, bounds, step=0.5, skip=0.06):
    kwargs = {'join_style': 'mitre', 'mitre_limit': 5.0} if join == 'mitre' else {'quad_segs': 8}
    shape = polygon.buffer(distance, **kwargs)
    x0, y0, x1, y1 = bounds
    columns = int(round((x1 - x0) / step))
    rows_count = int(round((y1 - y0) / step))
    rows = []
    for j in range(rows_count + 1):
        row = ''
        for i in range(columns + 1):
            point = Point(x0 + i * step + 0.013, y0 + j * step + 0.007)
            if shape.boundary.distance(point) < skip:
                row += '?'
            else:
                row += '1' if shape.contains(point) else '0'
        rows.append(row)
    rings = [list(polygon.exterior.coords)[:-1]] + [list(ring.coords)[:-1] for ring in polygon.interiors]
    cases.append(
        {
            'name': name,
            'kind': 'polygon',
            'rings': [[float(value) for xy in ring for value in xy] for ring in rings],
            'distance': distance,
            'joinStyle': join,
            'capStyle': 'round',
            'rawRings': [],
            'area': shape.area,
            'holeCount': sum(len(part.interiors) for part in getattr(shape, 'geoms', [shape])),
            'bounds': list(bounds),
            'step': step,
            'rows': rows,
        }
    )


dumbbell = Polygon(
    [(0, 0), (4, 0), (4, 1.6), (6, 1.6), (6, 0), (10, 0), (10, 4), (6, 4), (6, 2.4), (4, 2.4), (4, 4), (0, 4)]
)
add('spike polygon d=1 mitre limit', Polygon([(0, 0), (12, 2), (0, 4)]), 1.0, 'mitre', (-3, -3, 21, 7), step=0.25)
add(
    'notch polygon d=-0.8 mitre limit',
    Polygon([(0, 0), (10, 0), (10, 6), (5.4, 6), (5, 1.5), (4.6, 6), (0, 6)]),
    -0.8,
    'mitre',
    (-1, -1, 11, 7),
    step=0.25,
)
add('dumbbell split at the neck d=-0.45 round', dumbbell, -0.45, 'round', (-1, -1, 11, 5), step=0.25)

header = f"""// luma.gl
// SPDX-License-Identifier: MIT
// SPDX-FileCopyrightText: Copyright (c) vis.gl contributors

// Generated by test/oracles/geometry-buffer-mitre-limit.py with shapely {shapely.__version__}
// (GEOS {shapely.geos_version_string}): shapely.buffer areas, hole counts and membership grids
// (format of polygon-buffer-fixtures.ts). Do not edit by hand.

import type {{PolygonBufferFixture}} from './polygon-buffer-fixtures';

export const POLYGON_BUFFER_MITRE_LIMIT_FIXTURES: (PolygonBufferFixture & {{holeCount: number}})[] = """
with open(DESTINATION, 'w') as file:
    file.write(header + json.dumps(cases, indent=2) + ';\n')
for case in cases:
    print(case['name'], case['area'], case['holeCount'])
