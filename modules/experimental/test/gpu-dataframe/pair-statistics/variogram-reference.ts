import fixture from '../../oracles/fixtures/dataframe-variogram.json';

/** Derived tolerances of one reference scene (see `test/oracles/dataframe-variogram.py`). */
export type VariogramReferenceTolerance = {
  /** Fixed-point unit bound `u * 2^-25` of a Matheron bin mean. */
  semivarianceAbsolute: number;
  /** Relative f32 term rounding of a Matheron bin mean. */
  semivarianceRelative: number;
  /** Relative bound of a Cressie-Hawkins bin. */
  robustSemivarianceRelative: number;
  /** Absolute bound of a mean pair distance. */
  meanDistanceAbsolute: number;
};

/** scikit-gstat bins of one scene, lag-major. */
export type VariogramReferenceScene = {
  values: number[];
  semivariances: number[];
  robustSemivariances: number[];
  pairCounts: number[];
  meanDistances: number[];
  tolerance: VariogramReferenceTolerance;
};

/** The whole fixture: one lattice of positions shared by every scene. */
export type VariogramReferenceFixture = {
  generator: string;
  versions: Record<string, string>;
  positions: number[];
  bounds: [number, number, number, number];
  maximumDistance: number;
  lagCount: number;
  /** Smallest gap between a pair distance and a lag edge; GPU f32 distances keep every lag. */
  nearestEdgeDistance: number;
  outlierRow: number;
  scenes: Record<string, VariogramReferenceScene>;
};

/** scikit-gstat 1.0.24 Matheron and Cressie-Hawkins bins, generated by a committed script. */
export const VARIOGRAM_REFERENCE = fixture as unknown as VariogramReferenceFixture;

/** Returns a description of every bin outside its tolerance, or an empty list. */
export function getVariogramReferenceMismatches(
  label: string,
  result: {
    semivariances: ArrayLike<number>;
    pairCounts: ArrayLike<number>;
    meanDistances?: ArrayLike<number>;
    robustSemivariances?: ArrayLike<number>;
  },
  scene: VariogramReferenceScene
): string[] {
  const mismatches: string[] = [];
  const {tolerance} = scene;
  const check = (name: string, actual: number, expected: number, bound: number) => {
    if (!(Math.abs(actual - expected) <= bound)) {
      mismatches.push(`${label} ${name}: ${actual} != ${expected} (tolerance ${bound})`);
    }
  };
  for (let lag = 0; lag < scene.pairCounts.length; lag++) {
    if (result.pairCounts[lag] !== scene.pairCounts[lag]) {
      mismatches.push(
        `${label} pairCounts[${lag}]: ${result.pairCounts[lag]} != ${scene.pairCounts[lag]}`
      );
    }
    const gamma = scene.semivariances[lag];
    check(
      `semivariances[${lag}]`,
      result.semivariances[lag],
      gamma,
      tolerance.semivarianceAbsolute + tolerance.semivarianceRelative * Math.abs(gamma)
    );
    if (result.robustSemivariances) {
      const robust = scene.robustSemivariances[lag];
      check(
        `robustSemivariances[${lag}]`,
        result.robustSemivariances[lag],
        robust,
        tolerance.robustSemivarianceRelative * Math.abs(robust)
      );
    }
    if (result.meanDistances) {
      check(
        `meanDistances[${lag}]`,
        result.meanDistances[lag],
        scene.meanDistances[lag],
        tolerance.meanDistanceAbsolute
      );
    }
  }
  return mismatches;
}
