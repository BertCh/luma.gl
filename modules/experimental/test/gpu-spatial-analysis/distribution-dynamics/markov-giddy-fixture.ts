import fixtureJson from '../../oracles/fixtures/statistics-markov.json';
import {decodeOracleFixture} from '../../oracles/oracle-fixture';

/** giddy `homogeneity` Q and LR statistics, their p-values and degrees of freedom. */
export type MarkovHomogeneityReference = {
  Q: number;
  Qp: number;
  LR: number;
  LRp: number;
  dof: number;
};

/** Number of sparse (below the threshold) and empty (condition, from-state) rows. */
export type MarkovSparsityReference = {sparse: number; empty: number};

type ChainReference = {
  counts: number[];
  homogeneity: MarkovHomogeneityReference;
  steadyStates: number[];
  sparsity: MarkovSparsityReference;
};

type LisaReference = {values: number[]; counts: number[]; ignored: number; states: number[]};

const fixture = decodeOracleFixture<{
  generator: string;
  versions: Record<string, string>;
  tolerances: Record<
    'homogeneityStatistic' | 'pValue' | 'steadyState',
    {absolute: number; relative: number}
  >;
  reference: {
    a: ChainReference & {
      seed: number;
      classes: number[];
      conditions: number[];
      sparsityThreshold: number;
    };
    bGood: ChainReference & {giddyHomogeneity: MarkovHomogeneityReference};
    bAll: ChainReference & {giddyHomogeneity: MarkovHomogeneityReference};
    c1: LisaReference & {steadyState: number[]; giddyP: number[]};
    c2: LisaReference;
  };
}>(fixtureJson);

const {a, bGood, bAll, c1, c2} = fixture.reference;

/**
 * giddy 2.3.9 / esda 2.10 / libpysal 4.15 references generated by
 * `test/oracles/statistics-markov.py` (see its docstring for the scenes and layout notes).
 * `*_CLASSES`, `*_CONDITIONS` and `*_VALUES` are period-major (period t, row i at t * rows + i);
 * `*_STEADY_STATES` has the pooled chain first, then one chain per condition; `*_HOMOGENEITY` uses
 * the documented rule where an empty from-state adds 0 degrees of freedom (`*_GIDDY_HOMOGENEITY`
 * is giddy's own, which adds 1 per such row). LISA states: giddy quadrant 1..4, -1 = no state.
 */
export const MARKOV_FIXTURE_PROVENANCE = {
  generator: fixture.generator,
  versions: fixture.versions
};

