import fixtureJson from '../../oracles/fixtures/statistics-edge-policy.json';
import {decodeOracleFixture} from '../../oracles/oracle-fixture';

/** Absolute and relative bound of one compared quantity. */
export type EdgePolicyTolerance = {absolute: number; relative: number};

/** Randomization fields of one global statistic (NaN where the policy leaves it undefined). */
export type EdgePolicyGlobalStatistic = {
  statistic: number;
  expected: number;
  varianceRandomization: number;
  zRandomization: number;
  pRandomization: number;
};

/** One row of the global table (`GPUGlobalSpatialStatistics`, binary weights, islands kept). */
export type EdgePolicyGlobalCase = {
  name: string;
  policy: string;
  values: number[];
  /** Mask words, or NaN when the case has no mask. */
  mask: number[] | number;
  expected: {
    count: number;
    blackCount: number;
    moran: EdgePolicyGlobalStatistic;
    geary: EdgePolicyGlobalStatistic;
    getisOrdG: EdgePolicyGlobalStatistic;
    joinCount: {blackBlack: number; blackWhite: number; whiteWhite: number; joins: number};
  };
};

/** One row of the local table (`GPUHotSpotAnalysis` Gi* and `GPULocalMoran` on binary weights). */
export type EdgePolicyLocalCase = {
  name: string;
  policy: string;
  values: number[];
  mask: number[] | number;
  expected: {count: number; giStar: number[]; localI: number[]};
};

/**
 * Edge-policy tables (quality roadmap rule 22) of the core spatial statistics: NaN, +-Infinity and
 * -0 values, masks, empty input, n < 4 and constant values, with esda values on the analysis rows.
 * Generated by `test/oracles/statistics-edge-policy.py`; see its docstring for the policy.
 */
export const STATISTICS_EDGE_POLICY = decodeOracleFixture<{
  generator: string;
  versions: Record<string, string>;
  tolerances: Record<'statistic' | 'zScore' | 'pValue', EdgePolicyTolerance>;
  /** Binary symmetric neighbor lists of the 12-row ring. */
  rows: number[][];
  global: EdgePolicyGlobalCase[];
  local: EdgePolicyLocalCase[];
  parameters: {policy: string; rejectedSignificanceLevels: number[]};
}>(fixtureJson);

/** CSR of the ring, binary weights. */
export function getEdgePolicyWeights(): {
  offsets: Uint32Array;
  neighbors: Uint32Array;
  weights: Float32Array;
} {
  const offsets = [0];
  const neighbors: number[] = [];
  for (const row of STATISTICS_EDGE_POLICY.rows) {
    neighbors.push(...row);
    offsets.push(neighbors.length);
  }
  return {
    offsets: Uint32Array.from(offsets),
    neighbors: Uint32Array.from(neighbors),
    weights: new Float32Array(neighbors.length).fill(1)
  };
}

/** The case mask as uploaded words, or undefined when the case has none. */
export function getEdgePolicyMask(mask: number[] | number): Uint32Array | undefined {
  return Array.isArray(mask) ? Uint32Array.from(mask) : undefined;
}

/** `actual` is within `tolerance` of `expected`, and NaN exactly where `expected` is NaN. */
export function isWithinEdgePolicyTolerance(
  actual: number,
  expected: number,
  tolerance: EdgePolicyTolerance
): boolean {
  if (Number.isNaN(expected)) {
    return Number.isNaN(actual);
  }
  return (
    Math.abs(actual - expected) <= tolerance.absolute + tolerance.relative * Math.abs(expected)
  );
}
