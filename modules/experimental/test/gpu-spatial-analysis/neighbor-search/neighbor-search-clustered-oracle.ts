import fixtureJson from '../../oracles/fixtures/geometry-neighbor-search-clustered.json';
import {decodeOracleFixture} from '../../oracles/oracle-fixture';

/** CSR of one scipy cKDTree evaluation (ties by lowest id, rows ascending by id). */
export type ClusteredCSR = {
  offsets: number[];
  neighbors: number[];
  /** Exact integer squared distances. */
  distancesSquared: number[];
};

/** One scene of `geometry-neighbor-search-clustered.py`. */
export type ClusteredScene = {
  name: string;
  selfJoin: boolean;
  /** Integer coordinates; NaN rows are invalid. */
  positions: number[];
  /** Absent (decoded as NaN) or a 0/1 target mask. */
  mask: number[] | number;
  queryPositions: number[] | number;
  knn: Record<string, ClusteredCSR>;
  radius: Record<string, ClusteredCSR>;
};

const fixture = decodeOracleFixture<{
  generator: string;
  versions: Record<string, string>;
  bounds: number[];
  scenes: ClusteredScene[];
}>(fixtureJson);

/**
 * Clustered, duplicate, collinear and invalid-point neighbor sets from `scipy.spatial.cKDTree`,
 * generated by `test/oracles/geometry-neighbor-search-clustered.py`.
 */
export const NEIGHBOR_SEARCH_CLUSTERED_ORACLE = {
  bounds: fixture.bounds as [number, number, number, number],
  scenes: fixture.scenes,
  versions: fixture.versions
};
