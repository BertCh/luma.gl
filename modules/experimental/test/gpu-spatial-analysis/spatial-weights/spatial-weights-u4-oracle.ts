import fixtureJson from '../../oracles/fixtures/statistics-spatial-weights.json';
import {decodeOracleFixture} from '../../oracles/oracle-fixture';

export type WeightsOracle = {
  points: number[][];
  k: number;
  /** Per kernel: rows of [neighbor, distance, weight] without the self slot, h_i and K(0). */
  kernels: Record<
    string,
    {rows: [number, number, number][][]; bandwidth: number[]; selfWeight: number}
  >;
  islands: {
    islands: number[];
    cardinalities: number[];
    minCardinality: number;
    maxCardinality: number;
    s0: number;
    s1: number;
    s2: number;
  };
};

/** Neighbors (ascending by id) and weights of every row of one libpysal `W`. */
export type LibpysalRows = {neighbors: number[][]; weights: number[][]};

/** A polygon scene with its libpysal Queen and Rook contiguity. */
export type LibpysalContiguityScene = {
  /** Polygons of rings of `[x, y]` vertices. */
  polygons: [number, number][][][];
  queen: LibpysalRows;
  rook: LibpysalRows;
};

/** libpysal weights construction references (see `test/oracles/statistics-spatial-weights.py`). */
export type LibpysalConstructionReference = {
  contiguity: {
    squareGrid: LibpysalContiguityScene & {columns: number; rows: number};
    randomRectangles: LibpysalContiguityScene;
    holes: LibpysalContiguityScene;
  };
  /** `lat2W(height, width, rook)`, id = row * width + column. */
  lattice: {width: number; height: number; rook: LibpysalRows; queen: LibpysalRows};
  /** `KNN.from_array`; `distances` are float64 Euclidean distances per slot. */
  knn: LibpysalRows & {
    seed: number;
    positions: number[];
    k: number;
    bounds: [number, number, number, number];
    distances: number[][];
  };
  /** `DistanceBand(binary=True)` on the `knn` positions. */
  distanceBand: LibpysalRows & {threshold: number; distances: number[][]};
  /** `w.transform = 'r'` of the Queen square grid and of the kNN weights. */
  rowStandardized: {squareGridQueen: LibpysalRows; knn: LibpysalRows};
};

const fixture = decodeOracleFixture<{
  generator: string;
  versions: Record<string, string>;
  tolerances: {
    rowStandardizedWeight: {relative: number};
    distance: {relative: number};
    kernelWeightCpu: {absolute: number};
    kernelWeightGpu: {absolute: number};
  };
  reference: WeightsOracle;
  construction: LibpysalConstructionReference;
}>(fixtureJson);

/**
 * libpysal 4.15 `Kernel(fixed=False)` on kNN input, and islands, cardinalities and s0 / s1 / s2 of a
 * `W` built without zero-weight entries; generated by `test/oracles/statistics-spatial-weights.py`.
 */
export const WEIGHTS_ORACLE: WeightsOracle = fixture.reference;

/** libpysal Queen, Rook, `lat2W`, `KNN` and `DistanceBand` weights, binary and row standardized. */
export const LIBPYSAL_CONSTRUCTION_REFERENCE: LibpysalConstructionReference = fixture.construction;

/** Tolerances recorded by the generator, with their derivation in the generator docstring. */
export const LIBPYSAL_WEIGHTS_TOLERANCES = fixture.tolerances;
