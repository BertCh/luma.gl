import {GPUCommandGraph} from '@luma.gl/gpgpu/gpu-core';
import {getWebGPUTestDevice} from '@luma.gl/test-utils';
import {expect, it} from 'vitest';
import {GPUBufferSurface} from '../../../src/gpu-spatial-analysis';
import {readUint32, submitGraph} from '../../utils/gpu-contributor-test-utils';
import {
  createBufferGraph,
  createBufferResult,
  getPolygonsArea,
  isInsidePolygons,
  readResultPolygons
} from './polygon-buffer-test-utils';
import {POLYGON_BUFFER_FIXTURES, type PolygonBufferFixture} from './polygon-buffer-fixtures';

// Oracle: shapely.buffer areas and membership grids in polygon-buffer-fixtures.ts, generated by
// scratchpad/fix/work/W2A/buffer/fixtures.py (see the fixture header for the shapely version).

/** Relative area tolerance. Mitre cases are exact up to f32; round arcs differ by discretization. */
function getAreaTolerance(fixture: PolygonBufferFixture): number {
  return fixture.joinStyle === 'round' ? 5e-3 : 1e-4;
}

async function runFixture(fixture: PolygonBufferFixture) {
  const device = await getWebGPUTestDevice();
  if (!device) {
    return null;
  }
  const graph = new GPUCommandGraph(device, {id: `polygon-buffer-${fixture.name}`});
  const graphBuffers = createBufferGraph(device, graph);
  const result = createBufferResult(graphBuffers, 'result');
  const coordinates = fixture.rings.flat();
  const positions = graphBuffers.input(
    'positions',
    Float32Array.from(coordinates),
    'float32x2',
    coordinates.length / 2
  );
  const parameters = graphBuffers.input(
    'parameters',
    Float32Array.of(fixture.distance, 5, 0, 0),
    'float32',
    4
  );
  let boundaryOffsets = 0;
  const ringOffsets = [0, ...fixture.rings.map(ring => (boundaryOffsets += ring.length / 2))];
  const geometry =
    fixture.kind === 'line'
      ? {
          kind: 'lines' as const,
          positions,
          lineOffsets: graphBuffers.input(
            'line-offsets',
            Uint32Array.of(...ringOffsets),
            'uint32',
            ringOffsets.length
          )
        }
      : {
          kind: 'polygons' as const,
          positions,
          featureOffsets: graphBuffers.input('feature-offsets', Uint32Array.of(0, 1), 'uint32', 2),
          polygonOffsets: graphBuffers.input(
            'polygon-offsets',
            Uint32Array.of(0, fixture.rings.length),
            'uint32',
            2
          ),
          ringOffsets: graphBuffers.input(
            'ring-offsets',
            Uint32Array.of(...ringOffsets),
            'uint32',
            ringOffsets.length
          )
        };
  graph.add(
    new GPUBufferSurface({
      geometry,
      parameters,
      joinStyle: fixture.joinStyle,
      capStyle: fixture.capStyle,
      quadSegments: 8,
      vertexTolerance: 1e-5,
      capacity: {intersections: 1024, nodedSegments: 1024},
      output: result.output
    })
  );
  const compiled = graph.compile();
  submitGraph(device, compiled, undefined);
  const polygons = await readResultPolygons(result);
  const [overflow] = await readUint32(result.overflow, 1);
  const [requiredCount] = await readUint32(result.requiredCount, 1);
  compiled.destroy();
  for (const buffer of graphBuffers.buffers) {
    buffer.destroy();
  }
  return {polygons, overflow, requiredCount};
}

for (const fixture of POLYGON_BUFFER_FIXTURES) {
  it(`GPUBufferSurface matches shapely.buffer: ${fixture.name}`, async () => {
    const run = await runFixture(fixture);
    if (!run) {
      return;
    }
    expect(run.overflow).toBe(0);
    expect(run.requiredCount).toBeGreaterThanOrEqual(run.polygons.length);
    const area = getPolygonsArea(run.polygons);
    expect(Math.abs(area - fixture.area) / fixture.area).toBeLessThan(getAreaTolerance(fixture));
    const [x0, y0, x1, y1] = fixture.bounds;
    const columns = Math.round((x1 - x0) / fixture.step);
    const rows = Math.round((y1 - y0) / fixture.step);
    const mismatches: string[] = [];
    for (let row = 0; row <= rows; row++) {
      for (let column = 0; column <= columns; column++) {
        const expected = fixture.rows[row][column];
        if (expected === '?') {
          continue;
        }
        const x = x0 + column * fixture.step + 0.013;
        const y = y0 + row * fixture.step + 0.007;
        if (isInsidePolygons(x, y, run.polygons) !== (expected === '1')) {
          mismatches.push(`(${x}, ${y}) expected ${expected}`);
        }
      }
    }
    expect(mismatches).toEqual([]);
  });
}
