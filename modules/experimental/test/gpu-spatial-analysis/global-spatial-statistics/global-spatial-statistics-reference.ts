import fixtureJson from '../../oracles/fixtures/statistics-global-autocorrelation.json';
import {decodeOracleFixture} from '../../oracles/oracle-fixture';

/** One CSR row of a reference scene: neighbor ids and float32-exact weights. */
export type GlobalStatisticsReferenceRow = {neighbors: number[]; weights: number[]};

/** esda values of one configuration (`statistic`, `expected`, variances, z and p fields). */
export type GlobalStatisticsReferenceCase = {
  count: number;
  s0: number;
  s1: number;
  s2: number;
  mean: number;
  variance: number;
  moran: Record<string, number>;
  geary: Record<string, number>;
  getisOrdG?: Record<string, number>;
};

/** One join-count scene: esda counts and exhaustive-enumeration randomization moments. */
export type JoinCountReferenceScene = {
  name: string;
  rows: GlobalStatisticsReferenceRow[];
  /** 1 = black, 0 = white. */
  values: number[];
  blackCount: number;
  placementCount: number;
  blackBlack: number;
  blackWhite: number;
  whiteWhite: number;
  joins: number;
  expectedBlackBlack: number;
  varianceBlackBlack: number;
  zBlackBlack: number;
  pBlackBlack: number;
  expectedBlackWhite: number;
  varianceBlackWhite: number;
  zBlackWhite: number;
  pBlackWhite: number;
};

/** Absolute and relative bound of one compared quantity. */
export type GlobalStatisticsTolerance = {absolute: number; relative: number};

const fixture = decodeOracleFixture<{
  generator: string;
  versions: Record<string, string>;
  tolerances: Record<'statistic' | 'zScore' | 'pValue', GlobalStatisticsTolerance>;
  reference: {
    values: number[];
    islands: number[];
    masked: number[];
    rows: GlobalStatisticsReferenceRow[];
    keep: GlobalStatisticsReferenceCase;
    excludeSubset: GlobalStatisticsReferenceCase;
    standardizedMasked: GlobalStatisticsReferenceCase;
    binaryKeep: GlobalStatisticsReferenceCase;
    binaryExclude: GlobalStatisticsReferenceCase;
  };
  joinCounts: JoinCountReferenceScene[];
}>(fixtureJson);

/**
 * esda 2.10 / libpysal 4.15 global Moran, Geary and General G references generated by
 * `test/oracles/statistics-global-autocorrelation.py` (see its docstring for the scene). `keep` is
 * esda on the whole W (islands stay in n); `excludeSubset` is esda on W.subset without the island
 * rows; `standardizedMasked` is esda on the subset W without the masked rows, row-standardized
 * again; `binary*` are the same on binary W, where General G is defined.
 */
export const GLOBAL_STATISTICS_REFERENCE = fixture.reference;

/** esda join counts with exhaustive-enumeration randomization moments, from the same generator. */
export const JOIN_COUNT_REFERENCE = fixture.joinCounts;

/** Tolerances recorded by the generator. */
export const GLOBAL_STATISTICS_TOLERANCES = fixture.tolerances;
