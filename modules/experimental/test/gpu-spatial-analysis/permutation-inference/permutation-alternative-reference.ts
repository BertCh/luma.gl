import fixtureJson from '../../oracles/fixtures/statistics-permutation-alternative.json';
import {decodeOracleFixture} from '../../oracles/oracle-fixture';

/** esda p-values of one observed value against 20 simulated values. */
export type PermutationAlternativeReference = {
  observed: number;
  /** #{sim >= observed}. */
  greater: number;
  /** #{sim <= observed}. */
  lesser: number;
  directed: number;
  greaterP: number;
  lesserP: number;
  foldedP: number;
  /** True where esda `directed` differs from (min(greater, lesser) + 1) / (R + 1). */
  minRuleDiffers: boolean;
};

/**
 * esda 2.10 / libpysal 4.15 references generated by
 * `test/oracles/statistics-permutation-alternative.py` (see its docstring for the scenes).
 */
export type PermutationAlternativeFixture = {
  simulatedCount: number;
  /** The 20 simulated values of the `distinct_*` cases. */
  simulated: number[];
  alternatives: Record<string, PermutationAlternativeReference>;
  /** Moran's I randomization moments of the skewed x on a 10 x 10 rook lattice. */
  moran: {
    expectedI: number;
    varianceRandomization: number;
    chiSquareCritical: {df9: number; df99: number};
  };
};

const fixture = decodeOracleFixture<{
  generator: string;
  versions: Record<string, string>;
  tolerances: Record<'pValueDecimals' | 'expectedIDecimals' | 'varianceDecimals', number>;
  reference: PermutationAlternativeFixture;
}>(fixtureJson);

/** The esda reference values. */
export const PERMUTATION_ALTERNATIVE_REFERENCE = fixture.reference;

/** Decimal places the specs compare to, derived in the generator docstring. */
export const PERMUTATION_ALTERNATIVE_TOLERANCES = fixture.tolerances;

/** Script that wrote the fixture, and the package versions it ran with. */
export const PERMUTATION_ALTERNATIVE_PROVENANCE = {
  generator: fixture.generator,
  versions: fixture.versions
};
