import fixtureJson from '../../oracles/fixtures/statistics-spatial-weights-traces.json';
import {decodeOracleFixture} from '../../oracles/oracle-fixture';

/** Values of one scalar quantity per tested spatial parameter, keyed by the rho as text. */
type ByRho = Record<'-0.6' | '-0.3' | '0.2' | '0.5' | '0.9', number>;

/** `spreg.GM_Lag` and `spmultiplier` references of one row-standardized scene. */
type SpregReference = {
  rho: number;
  betas: number[];
  full: {multipliers: number[]; pow: number; impacts: number[][]};
  exact: {multipliers: number[]};
  simple: number[];
};

/** References of one weights scene. */
type TracesSceneReference = {
  powerTraces: number[];
  powerSums: number[];
  gramTraces: number[];
  logDeterminant: ByRho;
  multiplierTrace: ByRho;
  multiplierTotal: ByRho;
  spectralRadius: number;
};

const fixture = decodeOracleFixture<{
  generator: string;
  versions: Record<string, string>;
  tolerances: {regeneration: {absolute: number; relative: number}};
  maximumPower: number;
  reference: Record<'rawLattice', TracesSceneReference> &
    Record<'lattice' | 'knn60' | 'knn90', TracesSceneReference & {spreg: SpregReference}>;
}>(fixtureJson);

/**
 * Reference values for `GPUSpatialWeightsTraces` and `GPUSpatialLagImpacts`, generated by
 * `test/oracles/statistics-spatial-weights-traces.py` (numpy, scipy, spreg, libpysal; float64) on
 * the seeded scenes of `test/oracles/fixtures/statistics-spatial-weights-traces-scenes.json`, with
 * the float32-rounded weights the TypeScript generators produce:
 * - `lattice`: `createLagScene(12, 21, 0.5, true)` (row-standardized rook lattice, n = 144; bipartite,
 *   so odd traces are exactly zero);
 * - `rawLattice`: `createLagScene(10, 8, 0.12, false)` (binary rook lattice, spectral radius 3.84);
 * - `knn60`: `createNearestNeighborScene(60, 3, 13, 0.6, false)` (directed row-standardized kNN);
 * - `knn90`: `createNearestNeighborScene(90, 3, 29, 0.6, false)`.
 * Per scene: `powerTraces[q-1] = trace(W^q)` and `powerSums[q-1] = 1' W^q 1` for q = 1..12;
 * `gramTraces = [tr(W'W), tr(W'WW), tr((W'W)^2), sum_i c_i^2]`; `logDeterminant`,
 * `multiplierTrace` and `multiplierTotal` at each rho. `spreg` (row-standardized scenes) holds
 * `GM_Lag(y, X, w, w_lags=1)` rho and betas, `spmultiplier` `[direct, indirect, total]` for `'full'`
 * and `'simple'`, and `exact`, the general-W definitions. spreg `'power'` is not pinned: it stops
 * after the first term whose trace vanishes, which is wrong on the bipartite lattice.
 */
export const SPATIAL_WEIGHTS_TRACES_REFERENCE = fixture.reference;

/** Number of powers pinned in {@link SPATIAL_WEIGHTS_TRACES_REFERENCE}. */
export const SPATIAL_WEIGHTS_TRACES_REFERENCE_MAXIMUM_POWER = fixture.maximumPower;
