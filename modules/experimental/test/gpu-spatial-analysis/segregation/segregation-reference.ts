import fixtureJson from '../../oracles/fixtures/statistics-segregation.json';
import {decodeOracleFixture} from '../../oracles/oracle-fixture';

/** Absolute and relative bound of one compared quantity. */
export type OracleTolerance = {absolute: number; relative: number};

/** PySAL segregation indices of one scale; per-group arrays hold one value per group. */
export type SegregationIndicesReference = {
  entropy: number;
  multiD: number;
  D: number[];
  isolation: number[];
  atkinson: number[];
};

/**
 * PySAL `segregation` 2.6 references generated by `test/oracles/statistics-segregation.py` (see its
 * docstring for the scene). `counts` is unit-major (unit * groups + group) on a row-major grid;
 * `queen` is PySAL's spatially implicit indices with binary Queen weights and self weight 1.
 */
export type SegregationReference = {
  columns: number;
  rows: number;
  groups: number;
  counts: number[];
  aspatial: SegregationIndicesReference;
  queen: SegregationIndicesReference;
};

const fixture = decodeOracleFixture<{
  generator: string;
  versions: Record<string, string>;
  tolerances: Record<'entropy' | 'multiD' | 'D' | 'isolation' | 'atkinson', OracleTolerance>;
  reference: SegregationReference;
}>(fixtureJson);

/** The segregation package reference values. */
export const SEGREGATION_REFERENCE = fixture.reference;

/** Tolerances recorded by the generator, with their derivation in the generator docstring. */
export const SEGREGATION_TOLERANCES = fixture.tolerances;

/** Script that wrote the fixture, and the package versions it ran with. */
export const SEGREGATION_PROVENANCE = {generator: fixture.generator, versions: fixture.versions};
