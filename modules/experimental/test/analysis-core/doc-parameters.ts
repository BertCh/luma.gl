// A-22: generated "Parameters" subsections. For every exported contributor class with a packer, the
// generator writes the packer, its length constant and its settings fields with their TSDoc into
// the class's section of its doc page, between the MDX comments `{/* parameters: GPUClass ... */}`
// and `{/* /parameters */}` (the docs build as MDX, which rejects HTML comments). Only the text
// between the markers is generated; a class section without
// markers gets them appended at its end the first time the generator runs.
//
// Packers come from the analysis entry barrels. A class has a packer when
// - the packer is `get<Class>ParameterValues` or a variant (`get<Class>WordParameterValues`,
//   `get<Class>ToleranceParameterValues`), the class being the longest class name the stem starts
//   with, or
// - the class's source file imports the packer or its length constant (a layout shared by several
//   classes, such as permutation inference or the space-time tests), or
// - the class has a public `getParameterValues(settings)` method.
// The length is the exported `<STEM>_PARAMETER_LENGTH` constant, else the first exported
// `*_PARAMETER_LENGTH` constant the packer body uses, else `get<Stem>ParameterLength()`.
//
// Regenerate with `UPDATE_DOC_PARAMETERS=1 npx vitest run --project node
// modules/experimental/test/analysis-core/doc-parameters.node.spec.ts`.

/** The analysis entries whose packers are documented. */
const PACKER_ENTRIES = [
  '@luma.gl/experimental/gpu-spatial-analysis',
  '@luma.gl/experimental/gpu-network',
  '@luma.gl/experimental/gpu-terrain',
  '@luma.gl/experimental/gpu-raster',
  '@luma.gl/experimental/gpu-dataframe',
  '@luma.gl/experimental/geospatial'
] as const;

const PACKER_NAME = /^get(GPU\w+?)ParameterValues$/;
const BEGIN_MARKER = /^\{\/\* parameters: (GPU\w+) .*\*\/\}$/;
const MARKER_NOTE =
  'generated by modules/experimental/test/analysis-core/doc-parameters.ts from the TSDoc; do not edit';
const END_MARKER = '{/* /parameters */}';

/** One documented argument or settings field. */
export type ParameterField = {
  name: string;
  optional: boolean;
  type: string;
  description: string;
};

/** One packer of a class. */
export type ClassPacker = {
  /** Call shown in the docs, for example `getGPUKMeansParameterValues(settings)`. */
  call: string;
  /** Packed view format, from the return type. */
  format: 'float32' | 'uint32' | 'unknown';
  /** Length constant or function, with its value when it is a literal. */
  length: string | null;
  /** Identifiers a class file may import to read this layout (packer and length constant). */
  identifiers: string[];
  /** Arguments other than the settings object and the optional output array. */
  arguments: ParameterField[];
  /** Fields of the settings object (the first argument when it is an object type). */
  fields: ParameterField[];
};

/** Generated parameter documentation for one class. */
export type ClassParameters = {
  className: string;
  packers: ClassPacker[];
};

/** A rendered class section and where it goes. */
export type ParameterSection = {
  className: string;
  /** Doc page relative to `DOCS_ROOT`, or null when no section documents the class. */
  page: string | null;
  markdown: string;
};

/** Collects every class with a packer from the analysis entries. */
export function collectClassParameters(): ClassParameters[] {
  const probePath = join(DOCS_ROOT, '__doc_parameters__', 'entries.ts');
  const probe = PACKER_ENTRIES.map((entry, index) => `export * as entry${index} from '${entry}';`);
  const program = createVirtualProgram(
    new Map([[probePath, probe.join('\n')]]),
    getRepositoryCompilerOptions()
  );
  const checker = program.getTypeChecker();
  const sourceFile = program.getSourceFile(probePath);
  if (!sourceFile) {
    throw new Error('parameter probe missing');
  }

  const exports = new Map<string, typescript.Symbol>();
  for (const statement of sourceFile.statements) {
    if (
      typescript.isExportDeclaration(statement) &&
      statement.moduleSpecifier &&
      typescript.isStringLiteral(statement.moduleSpecifier)
    ) {
      const moduleSymbol = checker.getSymbolAtLocation(statement.moduleSpecifier);
      for (const symbol of moduleSymbol ? checker.getExportsOfModule(moduleSymbol) : []) {
        const target =
          symbol.flags & typescript.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
        if (!exports.has(symbol.name)) {
          exports.set(symbol.name, target);
        }
      }
    }
  }

  const classNames = [...exports]
    .filter(([name, symbol]) => /^GPU/.test(name) && symbol.flags & typescript.SymbolFlags.Class)
    .map(([name]) => name)
    .sort((left, right) => right.length - left.length);
  const byClass = new Map<string, ClassPacker[]>();
  const addPacker = (className: string, packer: ClassPacker): void => {
    byClass.set(className, [...(byClass.get(className) ?? []), packer]);
  };

  for (const [name, symbol] of [...exports].sort(([left], [right]) => left.localeCompare(right))) {
    const match = PACKER_NAME.exec(name);
    if (!match || !(symbol.flags & typescript.SymbolFlags.Function)) {
      continue;
    }
    const stem = match[1];
    const declaration = symbol.declarations?.find(typescript.isFunctionDeclaration);
    if (!declaration) {
      continue;
    }
    const length = getLength(checker, exports, stem, declaration);
    const packer = describePacker(checker, declaration, name, length?.text ?? null);
    packer.identifiers = [name, ...(length?.ownConstant ? [length.ownConstant] : [])];
    const owners = new Set<string>();
    const owner = classNames.find(className => stem.startsWith(className));
    if (owner) {
      owners.add(owner);
    }
    for (const className of classNames) {
      const imports = getImportedNames(exports.get(className));
      if (packer.identifiers.some(identifier => imports.has(identifier))) {
        owners.add(className);
      }
    }
    for (const className of owners) {
      addPacker(className, packer);
    }
  }

  for (const className of classNames) {
    const classSymbol = exports.get(className);
    const declaration = classSymbol?.declarations?.find(typescript.isClassDeclaration);
    const method = declaration?.members.find(
      (member): member is typescript.MethodDeclaration =>
        typescript.isMethodDeclaration(member) &&
        member.name.getText() === 'getParameterValues' &&
        !member.modifiers?.some(
          modifier =>
            modifier.kind === typescript.SyntaxKind.PrivateKeyword ||
            modifier.kind === typescript.SyntaxKind.ProtectedKeyword
        )
    );
    if (method) {
      addPacker(className, describePacker(checker, method, 'getParameterValues', null, true));
    }
  }

  return [...byClass]
    .map(([className, packers]) => ({className, packers}))
    .sort((left, right) => left.className.localeCompare(right.className));
}

/** Names a class's source file imports. */
function getImportedNames(classSymbol: typescript.Symbol | undefined): Set<string> {
  const names = new Set<string>();
  const sourceFile = classSymbol?.valueDeclaration?.getSourceFile();
  for (const statement of sourceFile?.statements ?? []) {
    const bindings = typescript.isImportDeclaration(statement)
      ? statement.importClause?.namedBindings
      : undefined;
    if (bindings && typescript.isNamedImports(bindings)) {
      for (const element of bindings.elements) {
        names.add((element.propertyName ?? element.name).text);
      }
    }
  }
  return names;
}

/** Finds the exported length constant or function of a packer. */
function getLength(
  checker: typescript.TypeChecker,
  exports: Map<string, typescript.Symbol>,
  stem: string,
  declaration: typescript.FunctionDeclaration
): {text: string; ownConstant?: string} | null {
  const constantName = `${stem.replace(/^GPU/, 'GPU_').replace(/([a-z0-9])([A-Z])/g, '$1_$2')}`;
  const normalized = `${constantName}_PARAMETER_LENGTH`.replace(/_/g, '').toLowerCase();
  const ownConstant = [...exports.keys()].find(
    name => /^[A-Z0-9_]+$/.test(name) && name.replace(/_/g, '').toLowerCase() === normalized
  );
  let constant = ownConstant;
  if (!constant) {
    const used: string[] = [];
    const visit = (node: typescript.Node): void => {
      if (typescript.isIdentifier(node) && /^GPU_\w*PARAMETER_LENGTH$/.test(node.text)) {
        used.push(node.text);
      }
      node.forEachChild(visit);
    };
    declaration.forEachChild(visit);
    constant = used.find(name => exports.has(name));
  }
  const symbol = constant ? exports.get(constant) : undefined;
  if (constant && symbol) {
    const valueDeclaration = symbol.valueDeclaration;
    const type = valueDeclaration
      ? checker.getTypeOfSymbolAtLocation(symbol, valueDeclaration)
      : null;
    const text = type?.isNumberLiteral() ? `\`${constant}\` (${type.value})` : `\`${constant}\``;
    return {text, ownConstant};
  }
  const functionName = `get${stem}ParameterLength`;
  return exports.has(functionName)
    ? {text: `\`${functionName}(...)\``, ownConstant: functionName}
    : null;
}

function describePacker(
  checker: typescript.TypeChecker,
  declaration: typescript.SignatureDeclaration,
  name: string,
  length: string | null,
  isMethod = false
): ClassPacker {
  const signature = checker.getSignatureFromDeclaration(declaration);
  const returnType = signature ? checker.typeToString(signature.getReturnType()) : '';
  const format = /Float32Array/.test(returnType)
    ? 'float32'
    : /Uint32Array/.test(returnType)
      ? 'uint32'
      : 'unknown';
  const parameterDocs = new Map(
    typescript
      .getJSDocTags(declaration)
      .filter(typescript.isJSDocParameterTag)
      .map(tag => [tag.name.getText(), getCommentText(tag.comment)])
  );
  const argumentsList: ParameterField[] = [];
  let fields: ParameterField[] = [];
  const shown: string[] = [];
  declaration.parameters.forEach((parameter, index) => {
    const parameterName = parameter.name.getText();
    const typeText = parameter.type ? normalizeText(parameter.type.getText()) : 'unknown';
    const optional = Boolean(parameter.questionToken || parameter.initializer);
    // The trailing output array (`target`) is an allocation detail, not an input.
    if (/^(Float32Array|Uint32Array)$/.test(typeText) && index > 0) {
      return;
    }
    shown.push(optional ? `${parameterName}?` : parameterName);
    const parameterType = checker.getTypeAtLocation(parameter);
    // Raster metadata (`grid`) is a shared contract documented once, not a settings object.
    if (
      index === 0 &&
      typeText !== 'GPURasterMetadata' &&
      isSettingsObject(checker, parameterType)
    ) {
      fields = getFields(checker, parameterType);
      return;
    }
    argumentsList.push({
      name: parameterName,
      optional,
      type: typeText,
      description: parameterDocs.get(parameterName) ?? ''
    });
  });
  return {
    call: `${isMethod ? 'instance.' : ''}${name}(${shown.join(', ')})`,
    format,
    length,
    identifiers: [],
    arguments: argumentsList,
    fields
  };
}

/** True for an object type with properties (not an array, number or raster metadata). */
function isSettingsObject(checker: typescript.TypeChecker, type: typescript.Type): boolean {
  const target = type.getNonNullableType();
  return (
    Boolean(target.flags & typescript.TypeFlags.Object || target.isIntersection()) &&
    !checker.isArrayType(target) &&
    !checker.isTupleType(target) &&
    target.getCallSignatures().length === 0 &&
    checker.getPropertiesOfType(target).length > 0
  );
}

function getFields(checker: typescript.TypeChecker, type: typescript.Type): ParameterField[] {
  return checker.getPropertiesOfType(type.getNonNullableType()).map(property => {
    const declaration = property.valueDeclaration ?? property.declarations?.[0];
    const typeNode =
      declaration &&
      (typescript.isPropertySignature(declaration) || typescript.isPropertyDeclaration(declaration))
        ? declaration.type
        : undefined;
    const typeText = typeNode
      ? typeNode.getText()
      : checker.typeToString(
          checker.getTypeOfSymbol(property),
          undefined,
          typescript.TypeFormatFlags.NoTruncation
        );
    const defaultTag = property
      .getJsDocTags(checker)
      .find(tag => tag.name === 'defaultValue' || tag.name === 'default');
    const defaultText = defaultTag ? getPartsText(defaultTag.text ?? []) : '';
    const description = getPartsText(property.getDocumentationComment(checker));
    return {
      name: property.name,
      optional: Boolean(property.flags & typescript.SymbolFlags.Optional),
      type: normalizeText(typeText),
      description: defaultText ? `${description} Default: ${defaultText}.`.trim() : description
    };
  });
}

/** Renders TSDoc display parts as Markdown: `{@link X}` becomes `` `X` ``. */
function getPartsText(parts: readonly typescript.SymbolDisplayPart[]): string {
  let text = '';
  for (const part of parts) {
    if (part.kind === 'link') {
      continue;
    }
    text += part.kind === 'linkName' ? `\`${part.text}\`` : part.text;
  }
  return normalizeText(text);
}

function getCommentText(
  comment: string | typescript.NodeArray<typescript.JSDocComment> | undefined
): string {
  if (!comment) {
    return '';
  }
  if (typeof comment === 'string') {
    return normalizeText(comment.replace(/^-\s*/, ''));
  }
  return normalizeText(
    comment
      .map(part =>
        typescript.isJSDocLink(part) ||
        typescript.isJSDocLinkCode(part) ||
        typescript.isJSDocLinkPlain(part)
          ? `\`${part.name?.getText() ?? part.text}\``
          : part.text
      )
      .join('')
      .replace(/^-\s*/, '')
  );
}

function normalizeText(text: string): string {
  return text.replace(/\s+/g, ' ').trim();
}

function escapeCell(text: string): string {
  return text.replace(/\|/g, '\\|');
}

/** Renders one class's subsection body (without the markers). */
export function renderClassParameters(parameters: ClassParameters, headingLevel: number): string {
  const lines = [`${'#'.repeat(headingLevel)} \`${parameters.className}\` parameters`, ''];
  for (const packer of parameters.packers) {
    const format = packer.format === 'unknown' ? '' : ` \`${packer.format}\``;
    const length = packer.length
      ? `${packer.length}${format} values`
      : `the${format} parameter view`;
    lines.push(`- Packer: \`${packer.call}\`, writes ${length}.`);
    for (const argument of packer.arguments) {
      const description = argument.description
        ? `: ${argument.description}`
        : argument.type === 'GPURasterMetadata'
          ? ': the frame grid, which supplies the cell size and row edges'
          : '';
      lines.push(`  - \`${argument.name}\` (\`${argument.type}\`)${description}`);
    }
  }
  // A class method that packs the same settings as a function packer shares its table.
  const tableKeys = new Set<string>();
  const tables = parameters.packers.filter(packer => {
    const key = JSON.stringify(packer.fields);
    const isNew = packer.fields.length > 0 && !tableKeys.has(key);
    tableKeys.add(key);
    return isNew;
  });
  for (const packer of tables) {
    lines.push('', `Settings of \`${packer.call.replace(/\(.*$/, '')}\`:`, '');
    lines.push('| Field | Type | Description |', '|---|---|---|');
    for (const field of packer.fields) {
      const name = `\`${field.name}\`${field.optional ? ' (optional)' : ''}`;
      lines.push(
        `| ${name} | \`${escapeCell(field.type)}\` | ${escapeCell(field.description) || '-'} |`
      );
    }
  }
  return lines.join('\n');
}

type DocHeading = {page: string; line: number; level: number; text: string};

function getHeadings(page: string, lines: string[]): DocHeading[] {
  const headings: DocHeading[] = [];
  let inFence = false;
  lines.forEach((line, index) => {
    if (/^\s*```/.test(line)) {
      inFence = !inFence;
    }
    const match = !inFence && /^(#{2,4}) (.*)$/.exec(line);
    if (match) {
      headings.push({page, line: index, level: match[1].length, text: match[2]});
    }
  });
  return headings;
}

/** Pages that index classes without documenting them, so they never hold a subsection. */
const INDEX_PAGES = new Set([
  'gpu-spatial-analysis-cross-reference.md',
  'gpu-spatial-analysis/README.md',
  'gpu-spatial-analysis/operators.md'
]);

/**
 * Finds the section that documents a class: the first heading naming it in backticks, else the
 * section whose body names it most often (the summary sections that cover several classes).
 */
function findClassHeading(
  className: string,
  headingsByPage: Map<string, DocHeading[]>,
  linesByPage: Map<string, string[]>
): DocHeading | null {
  const pattern = new RegExp(`\`${className}\`(?!\\w)`, 'g');
  const candidates = [...headingsByPage].filter(([page]) => !INDEX_PAGES.has(page));
  for (const [, headings] of candidates) {
    const heading = headings.find(
      candidate => !/ parameters$/.test(candidate.text) && candidate.text.match(pattern)
    );
    if (heading) {
      return heading;
    }
  }
  let best: {heading: DocHeading; count: number} | null = null;
  for (const [page, headings] of candidates) {
    const lines = linesByPage.get(page) ?? [];
    headings.forEach((heading, index) => {
      const end = headings[index + 1]?.line ?? lines.length;
      // Table rows are indexes (comparison tables), not documentation.
      const count = lines
        .slice(heading.line + 1, end)
        .filter(line => !line.trimStart().startsWith('|'))
        .reduce((total, line) => total + (line.match(pattern)?.length ?? 0), 0);
      if (count > 0 && (!best || count > best.count)) {
        best = {heading, count};
      }
    });
  }
  return (best as {heading: DocHeading} | null)?.heading ?? null;
}

/**
 * Returns each analysis page as it should be: generated blocks refreshed in place, and blocks for
 * classes that have none appended to their section. Also returns the classes no section documents.
 */
export function generateDocPages(): {pages: Map<string, string>; undocumented: string[]} {
  const classParameters = collectClassParameters();
  const linesByPage = new Map<string, string[]>(
    ANALYSIS_DOC_PAGES.map(page => [page, readDocPage(page).split('\n')])
  );
  const headingsByPage = new Map(
    [...linesByPage].map(([page, lines]) => [page, getHeadings(page, lines)])
  );
  const undocumented: string[] = [];
  // Insertions per page: line index → blocks, applied bottom-up so indexes stay valid.
  const insertions = new Map<string, Map<number, string[]>>();
  const generated = new Map(classParameters.map(entry => [entry.className, entry]));
  const existing = new Set<string>();

  for (const lines of linesByPage.values()) {
    for (const line of lines) {
      const match = BEGIN_MARKER.exec(line);
      if (match) {
        existing.add(match[1]);
      }
    }
  }

  for (const entry of classParameters) {
    if (existing.has(entry.className)) {
      continue;
    }
    const heading = findClassHeading(entry.className, headingsByPage, linesByPage);
    if (!heading) {
      undocumented.push(entry.className);
      continue;
    }
    const headings = headingsByPage.get(heading.page) ?? [];
    const next = headings.find(
      candidate => candidate.line > heading.line && candidate.level <= heading.level
    );
    const lines = linesByPage.get(heading.page) ?? [];
    let end = next ? next.line : lines.length;
    while (end > heading.line + 1 && lines[end - 1].trim() === '') {
      end--;
    }
    const pageInsertions = insertions.get(heading.page) ?? new Map<number, string[]>();
    const block = [
      '',
      getBeginMarker(entry.className),
      '',
      renderClassParameters(entry, Math.min(heading.level + 1, 6)),
      '',
      END_MARKER
    ].join('\n');
    pageInsertions.set(end, [...(pageInsertions.get(end) ?? []), block]);
    insertions.set(heading.page, pageInsertions);
  }

  const pages = new Map<string, string>();
  for (const [page, originalLines] of linesByPage) {
    const lines = [...originalLines];
    for (const [index, blocks] of [...(insertions.get(page) ?? [])].sort(([a], [b]) => b - a)) {
      lines.splice(index, 0, ...blocks.join('\n').split('\n'));
    }
    pages.set(page, refreshBlocks(lines, generated).join('\n'));
  }
  return {pages, undocumented};
}

function getBeginMarker(className: string): string {
  return `{/* parameters: ${className} ${MARKER_NOTE} */}`;
}

/** Rewrites the text between every marker pair; removes blocks whose class has no packer. */
function refreshBlocks(lines: string[], generated: Map<string, ClassParameters>): string[] {
  const output: string[] = [];
  const headings = getHeadings('', lines);
  for (let index = 0; index < lines.length; index++) {
    const match = BEGIN_MARKER.exec(lines[index]);
    if (!match) {
      output.push(lines[index]);
      continue;
    }
    let end = index + 1;
    while (end < lines.length && lines[end] !== END_MARKER) {
      end++;
    }
    if (end === lines.length) {
      throw new Error(`unterminated parameters block for ${match[1]}`);
    }
    const entry = generated.get(match[1]);
    if (entry) {
      const owner = [...headings]
        .reverse()
        .find(heading => heading.line < index && !/ parameters$/.test(heading.text));
      const level = Math.min((owner?.level ?? 2) + 1, 6);
      output.push(
        getBeginMarker(entry.className),
        '',
        renderClassParameters(entry, level),
        '',
        END_MARKER
      );
    } else if (output.at(-1) === '') {
      output.pop();
    }
    index = end;
  }
  return output.join('\n').split('\n');
}
