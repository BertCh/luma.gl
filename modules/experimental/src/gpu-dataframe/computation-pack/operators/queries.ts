/** Primary sum output; the acceptance mask already includes selection, validity and finiteness. */
function sumFormula(element: string, grouped: boolean): GPUComputationFormulaRef {
  return {
    id: `gpu-dataframe:${element}`,
    derivation: 'curated',
    tex: grouped
      ? String.raw`\term{sum}{S}_g = \sum_{i:\term{key}{k}_i=g,\;\term{accepted}{a}_i\ne0}\term{value}{x}_i`
      : String.raw`\term{sum}{S} = \sum_{i:\term{accepted}{a}_i\ne0}\term{value}{x}_i`,
    ascii: `sum${grouped ? '[g]' : ''} = sum(value[i] for accepted rows${grouped ? ' with key[i] = g in the dense group domain' : ''}); null when no finite, selected, valid values contribute; stored sum is zero for empty input; float32 accumulation rounds each addition${grouped ? '' : '; native integer sums wrap to 32 bits'}`,
    symbols: [
      {id: 'sum', role: 'output', binding: 'wgsl:outputValues'},
      {id: 'value', role: 'input', binding: 'wgsl:inputValues'},
      {id: 'accepted', role: 'input', binding: grouped ? 'wgsl:selectionMask' : 'wgsl:inputMask'},
      ...(grouped ? [{id: 'key', role: 'input' as const, binding: 'wgsl:groupKeys'}] : [])
    ]
  };
}

function makeEntry(
  descriptor: DataFrameOperatorEntry['descriptor'],
  stages: DataFrameOperatorEntry['stages'],
  formula: DataFrameOperatorEntry['formula'],
  sourceFiles: string[],
  datumKinds: DataFrameOperatorEntry['datumKinds'] = [row]
): DataFrameOperatorEntry {
  return {
    family: 'queries',
    descriptor,
    stages,
    formula,
    sourceFiles,
    datumKinds,
    guards: [],
    choices: []
  };
}

